"""Write the normalized Q38 Hann half-window to stdout."""

from math import cos, pi, sqrt

CENTER = 139
hann = [0.5 - 0.5 * cos(pi * i / CENTER) for i in range(CENTER + 1)]
power = 2 * sum(w * w for w in hann[:-1]) + hann[-1] ** 2
scale = (1 << 38) / sqrt(512 * power)
weights = [round(w * scale) for w in hann]

# Fifth differences fit in int8_t and reconstruct every rounded Q38 tap.
differences = [weights]
for _ in range(5):
    differences.append([b - a for a, b in zip(differences[-1], differences[-1][1:])])
assert all(-128 <= d <= 127 for d in differences[-1])

print("""// SPDX-License-Identifier: MIT
// Copyright (c) 2026 The c2fx Authors
// Generated by tools/make_analysis_window.py. Do not edit.

#include "c2fx_window.h"

/* Fifth forward differences of the symmetric 279-point Hann half-window. */
static const int8_t hann_delta5[135] = {""")
for i in range(0, len(differences[-1]), 16):
    print("    " + ", ".join(str(d) for d in differences[-1][i:i + 16]) + ",")
print("""};

void c2fx_hann_q38(int32_t half[C2FX_ANALYSIS_CENTER + 1])
{""")
for name, values in zip(("tap", "d1", "d2", "d3", "d4"), differences):
    print(f"    int32_t {name} = {values[0]};")
print("""
    for (int i = 0; i <= C2FX_ANALYSIS_CENTER; i++) {
        half[i] = tap;
        tap += d1;
        d1 += d2;
        d2 += d3;
        d3 += d4;
        if (i < 135) {
            d4 += hann_delta5[i];
        }
    }
}""")
