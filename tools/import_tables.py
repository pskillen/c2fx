"""Import Codec 2 3200 LSP quantizer tables from the black-box kit codebook files."""

from __future__ import annotations

import argparse
import filecmp
import hashlib
import os
import tempfile
from pathlib import Path

UPSTREAM_URL = "https://github.com/drowe67/codec2"
UPSTREAM_COMMIT = "310777b1c6f1af0bc7c72f5b32f80f6fd9136962"

LSP_COUNT = 10
ENTRIES_PER_LSP = 32

EXPECTED_SHA256: dict[str, str] = {
    "dlsp1.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp2.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp3.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp4.txt": "4ea3cc664caa017150f9bdf4d75a67db67abd7b9b2745baa577ed4a6604776ad",
    "dlsp5.txt": "4ea3cc664caa017150f9bdf4d75a67db67abd7b9b2745baa577ed4a6604776ad",
    "dlsp6.txt": "4ea3cc664caa017150f9bdf4d75a67db67abd7b9b2745baa577ed4a6604776ad",
    "dlsp7.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp8.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp9.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
    "dlsp10.txt": "6c8563ad9adedadeed06acae4dd0fed981981cd75953de54c71a262a15768334",
}


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def codebook_dir() -> Path:
    base = os.environ.get("C2FX_BLACKBOX")
    if not base:
        raise SystemExit("C2FX_BLACKBOX is not set")
    path = Path(base) / "codebook"
    if not path.is_dir():
        raise SystemExit(f"codebook directory not found: {path}")
    return path


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_dlsp(path: Path, name: str) -> list[int]:
    expected = EXPECTED_SHA256[name]
    actual = sha256_file(path)
    if actual != expected:
        raise SystemExit(f"{name}: SHA-256 mismatch (got {actual}, expected {expected})")

    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        raise SystemExit(f"{name}: empty file")
    header = lines[0].split()
    if len(header) != 2 or header != ["1", "32"]:
        raise SystemExit(f"{name}: bad header {lines[0]!r}, expected '1 32'")

    values: list[int] = []
    for line in lines[1:]:
        line = line.strip()
        if not line:
            continue
        try:
            value = int(line, 10)
        except ValueError as exc:
            raise SystemExit(f"{name}: not an integer: {line!r}") from exc
        if value < -32768 or value > 32767:
            raise SystemExit(f"{name}: value {value} does not fit int16")
        values.append(value)

    if len(values) != ENTRIES_PER_LSP:
        raise SystemExit(f"{name}: expected {ENTRIES_PER_LSP} values, got {len(values)}")
    return values


def load_tables(codebook: Path) -> list[list[int]]:
    tables: list[list[int]] = []
    for index in range(1, LSP_COUNT + 1):
        name = f"dlsp{index}.txt"
        tables.append(read_dlsp(codebook / name, name))
    return tables


def provenance_lines() -> list[str]:
    lines = [
        "Generated by tools/import_tables.py; do not edit.",
        f"Upstream: {UPSTREAM_URL}",
        f"Commit:   {UPSTREAM_COMMIT}",
    ]
    for index in range(1, LSP_COUNT + 1):
        name = f"dlsp{index}.txt"
        lines.append(f"Source:   {name}  SHA-256 {EXPECTED_SHA256[name]}")
    lines.append(
        "MIT grant from the Codec 2 authors: not yet requested (see NOTICE)."
    )
    return lines


def write_header(path: Path) -> None:
    text = """\
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 The c2fx Authors

#ifndef C2FX_C2_3200_TAB_H
#define C2FX_C2_3200_TAB_H

#include <stdint.h>

/* LSP quantizer codebooks for Codec 2 3200 (Hz). */
extern const int16_t c2fx_lsp_tab[10][32];

#endif
"""
    path.write_text(text, encoding="utf-8")


def format_row(values: list[int]) -> str:
    parts = ", ".join(str(v) for v in values)
    return f"    {{ {parts} }}"


def write_source(path: Path, tables: list[list[int]]) -> None:
    comment = "\n".join(f"// {line}" for line in provenance_lines())
    rows = ",\n".join(format_row(row) for row in tables)
    text = f"""\
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 The c2fx Authors

{comment}

#include <stdint.h>

#include "c2_3200_tab.h"

const int16_t c2fx_lsp_tab[10][32] = {{
{rows}
}};
"""
    path.write_text(text, encoding="utf-8")


def generate(out_dir: Path) -> None:
    codebook = codebook_dir()
    tables = load_tables(codebook)
    out_dir.mkdir(parents=True, exist_ok=True)
    write_header(out_dir / "c2_3200_tab.h")
    write_source(out_dir / "c2_3200_tab.c", tables)


def check() -> None:
    root = repo_root()
    expected = root / "src" / "tables"
    for name in ("c2_3200_tab.c", "c2_3200_tab.h"):
        if not (expected / name).is_file():
            raise SystemExit(f"missing tracked file: {expected / name}")

    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        generate(tmp_dir)
        for name in ("c2_3200_tab.c", "c2_3200_tab.h"):
            if not filecmp.cmp(expected / name, tmp_dir / name, shallow=False):
                raise SystemExit(
                    f"generated {name} differs from {expected / name}; "
                    "run tools/import_tables.py"
                )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate to a temp dir and compare with src/tables/",
    )
    args = parser.parse_args()

    if args.check:
        check()
        print("import_tables: ok")
        return

    out = repo_root() / "src" / "tables"
    generate(out)
    print(f"wrote {out / 'c2_3200_tab.c'} and {out / 'c2_3200_tab.h'}")


if __name__ == "__main__":
    main()